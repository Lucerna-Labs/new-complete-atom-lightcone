import subprocess
import sys


def run(candidate):
    calls = CASES + [CASES[0], CASES[11], CASES[3]]
    payload = base64.b64encode(json.dumps([args for _,args,_ in calls]).encode()).decode()
    runner = r'''import base64,copy,importlib.util,json,sys
spec=importlib.util.spec_from_file_location("candidate",sys.argv[1]);m=importlib.util.module_from_spec(spec);sys.modules[spec.name]=m;spec.loader.exec_module(m)
def fingerprint(value):
    if type(value) is dict and all(type(key) is str for key in value):
        return ("dict",tuple((key,fingerprint(value[key])) for key in sorted(value)))
    if type(value) is list:
        return ("list",tuple(fingerprint(item) for item in value))
    if type(value) in (str,int,type(None)):
        return (type(value).__name__,value)
    raise TypeError("value outside the exact input/output types")
values=[];unchanged=True
for args in json.loads(base64.b64decode(sys.argv[2])):
    supplied=copy.deepcopy(args);before=fingerprint(supplied)
    value=m.sc_witness(*supplied);fingerprint(value);values.append(value);unchanged=unchanged and fingerprint(supplied)==before
print("__RESULT__"+json.dumps({"values":values,"unchanged":unchanged}))'''
    try:
        result = subprocess.run([sys.executable,"-B","-c",runner,str(pathlib.Path(candidate).resolve()),payload],
                                capture_output=True,text=True,timeout=5)
        lines = [line[len("__RESULT__"):] for line in result.stdout.splitlines() if line.startswith("__RESULT__")]
        return json.loads(lines[-1]) if result.returncode == 0 and lines else None
    except (OSError,subprocess.TimeoutExpired,ValueError):
        return None


def passes(result):
    expected = [want for _,_,want in CASES] + [CASES[0][2],CASES[11][2],CASES[3][2]]
    return (type(result) is dict and set(result)=={"values","unchanged"}
            and result["unchanged"] is True and type(result["values"]) is list
            and result["values"]==expected
            and all(x is None or (type(x) is list and all(type(v) is str for v in x)) for x in result["values"]))

